// Requires tests.browser_server; never run against the user's normal data server.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8001';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: 'Asia/Shanghai', permissions: ['clipboard-read', 'clipboard-write'] });
    assert.ok((await context.request.put(base + '/api/profile', { headers: { 'X-Work-Report': '1' }, data: { name: '回归测试', role: '产品经理', dept: '' } })).ok());
    const page = await context.newPage(), errors = [], consoleErrors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') consoleErrors.push(m.text()); });
    await page.clock.setFixedTime(new Date('2026-10-20T12:00:00+08:00'));
    await page.goto(base + '/#daily');
    await page.locator('#today-display').filter({ hasText: '2026' }).waitFor();
    assert.match(await page.title(), /汇报有方/);
    await page.locator('#account-trigger').click();
    await page.locator('#account-dropdown [data-open-settings="api"]').click();
    assert.equal(await page.locator('#model-api-key').inputValue(), '');
    const connection = page.waitForResponse(r => r.url().endsWith('/api/model-settings/test'));
    await page.locator('#test-model').click();
    assert.equal((await (await connection).json()).status, 'ok');
    await page.keyboard.press('Escape');
    await page.locator('#daily-trigger').click();
    await page.locator('[data-day="2026-10-21"]').click();
    await page.waitForFunction(() => !document.querySelector('#daily-notes').readOnly);
    await page.locator('#daily-notes').fill('完成需求评审，整理项目成果。');
    await page.locator('#file-input').setInputFiles({ name: '评审记录.txt', mimeType: 'text/plain', buffer: Buffer.from('完成需求评审，已整理成果。') });
    await page.locator('.file-row').filter({ hasText: '评审记录.txt' }).waitFor();
    await page.waitForFunction(() => !document.querySelector('#daily-generate').disabled);
    await page.locator('#daily-generate').click();
    await page.locator('#daily-report').filter({ hasText: '整理本日工作' }).waitFor();
    await page.waitForFunction(() => document.querySelector('#daily-report').isContentEditable);
    await page.locator('#daily-report').click();
    await page.keyboard.press('Control+End');
    await page.keyboard.insertText('已人工核对。');
    const saved = page.waitForResponse(r => r.url().endsWith('/api/reports/daily/2026-10-21') && r.request().method() === 'PUT');
    await page.locator('[data-save-report="daily"]').click();
    const daily = await (await saved).json();
    assert.equal(daily.files.length, 1);
    assert.match(daily.points[0].text, /已人工核对/);
    await page.waitForFunction(() => !document.querySelector('#daily-copy').disabled);
    await page.locator('#daily-copy').click();
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /已人工核对/);
    const download = page.waitForEvent('download');
    await page.locator('#daily-download').click();
    const zip = await download;
    assert.match(zip.suggestedFilename(), /^20261021_产品经理_回归测试_工作汇报.zip$/);
    assert.equal((await fs.readFile(await zip.path())).subarray(0, 2).toString(), 'PK');
    await page.locator('.menu-leaf[data-route="weekly"]').click();
    await page.locator('#weekly-generate').click();
    await page.locator('#weekly-report').filter({ hasText: '汇总本周工作' }).waitFor();
    const weeklySave = page.waitForResponse(r => r.url().includes('/api/reports/weekly/') && r.request().method() === 'PUT');
    await page.locator('[data-save-report="weekly"]').click();
    const weekly = await (await weeklySave).json();
    assert.ok(weekly.files.some(f => f.name === '评审记录.txt'));
    await page.reload();
    await page.locator('#weekly-report').filter({ hasText: '汇总本周工作' }).waitFor();
    await page.locator('.menu-leaf[data-route="history"]').click();
    const filter = page.waitForResponse(r => r.url().includes('on_date=2026-10-21'));
    await page.locator('#history-date').fill('2026-10-21');
    await page.locator('#history-date').dispatchEvent('change');
    assert.equal((await (await filter).json()).total, 2);
    await page.waitForFunction(() => document.querySelectorAll('.history-card').length === 2);
    await page.locator('#history-clear-date').click();
    assert.equal(await page.locator('#history-date').inputValue(), '');
    assert.equal(await page.locator('#history-date').evaluate(e => getComputedStyle(e).color), 'rgba(0, 0, 0, 0)');
    await page.setViewportSize({ width: 1280, height: 720 });
    const rect = await page.locator('#history-date').boundingBox();
    assert.ok(rect.x + rect.width < 1280);
    assert.deepEqual(errors, []);
    assert.deepEqual(consoleErrors, []);
    console.log('PASS real UI/API workflow: model connection, upload, generation, edit, save, copy, ZIP, weekly sources, weekly generation/save/restore, date filter/clear, console, 1440/1280 viewports');
  } finally { await browser.close(); }
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
